-- Additive, repeatable. Existing attempts/mistakes and question IDs are retained.
begin;
create table if not exists public.mistake_reviews (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 question_id text not null,
 cause text not null default '未分类' check(cause in ('未分类','概念不清','计算错误','条件遗漏','方法不会')),
 status text not null default '待复习' check(status in ('待复习','复练中','已掌握')),
 review_count integer not null default 0 check(review_count>=0),
 correct_streak integer not null default 0 check(correct_streak>=0),
 last_attempt_id bigint, last_result boolean,
 updated_at timestamptz not null default now(), unique(user_id,question_id)
);
create table if not exists public.mistake_review_events (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 question_id text not null, cause text not null, status text not null,
 event_type text not null, result boolean, created_at timestamptz not null default now()
);
create index if not exists mistake_review_events_owner_question on public.mistake_review_events(user_id,question_id,created_at desc);
create table if not exists public.weekly_review_plans (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 week_start date not null, grade text not null check(grade in ('grade1','grade2','grade3')),
 tasks jsonb not null check(jsonb_typeof(tasks)='array' and jsonb_array_length(tasks)<=5),
 created_at timestamptz not null default now(), unique(user_id,week_start,grade)
);
create table if not exists public.chapter_assessments (
 id uuid primary key, user_id uuid not null references auth.users(id) on delete cascade,
 chapter text not null, title text not null, started_at timestamptz not null,
 submitted_at timestamptz not null, objective_score integer not null check(objective_score between 0 and 36),
 self_score integer not null check(self_score between 0 and 24),
 payload jsonb not null, created_at timestamptz not null default now()
);
create index if not exists chapter_assessments_owner_time on public.chapter_assessments(user_id,created_at desc);
alter table public.mistake_reviews enable row level security;
alter table public.mistake_review_events enable row level security;
alter table public.weekly_review_plans enable row level security;
alter table public.chapter_assessments enable row level security;
revoke all on public.mistake_reviews,public.mistake_review_events,public.weekly_review_plans,public.chapter_assessments from anon,authenticated;
grant select on public.mistake_reviews,public.mistake_review_events,public.weekly_review_plans,public.chapter_assessments to authenticated;
grant insert(user_id,question_id,cause,status),update(cause,status) on public.mistake_reviews to authenticated;
grant insert(user_id,week_start,grade,tasks) on public.weekly_review_plans to authenticated;
grant usage on sequence public.mistake_reviews_id_seq,public.weekly_review_plans_id_seq to authenticated;
drop policy if exists own_reviews on public.mistake_reviews;
create policy own_reviews on public.mistake_reviews to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());
drop policy if exists own_review_events on public.mistake_review_events;
create policy own_review_events on public.mistake_review_events for select to authenticated using(user_id=auth.uid());
drop policy if exists own_weekly_plans on public.weekly_review_plans;
create policy own_weekly_plans on public.weekly_review_plans to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());
drop policy if exists own_assessments on public.chapter_assessments;
create policy own_assessments on public.chapter_assessments for select to authenticated using(user_id=auth.uid());

create or replace function public.log_mistake_review() returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
begin
 insert into public.mistake_review_events(user_id,question_id,cause,status,event_type,result)
 values(new.user_id,new.question_id,new.cause,new.status,
 case when tg_op='INSERT' then 'created' when new.last_attempt_id is distinct from old.last_attempt_id then 'practice' else 'manual' end,
 case when tg_op='UPDATE' and new.last_attempt_id is distinct from old.last_attempt_id then new.last_result else null end);
 return new;
end $$;
revoke all on function public.log_mistake_review() from public,anon,authenticated;
drop trigger if exists log_mistake_review on public.mistake_reviews;
create trigger log_mistake_review after insert or update on public.mistake_reviews for each row execute function public.log_mistake_review();
create or replace function public.touch_mistake_review() returns trigger language plpgsql set search_path=public,pg_temp as $$
begin new.updated_at=clock_timestamp(); return new; end $$;
revoke all on function public.touch_mistake_review() from public,anon,authenticated;
drop trigger if exists touch_mistake_review on public.mistake_reviews;
create trigger touch_mistake_review before insert or update on public.mistake_reviews for each row execute function public.touch_mistake_review();

insert into public.mistake_reviews(user_id,question_id)
 select distinct user_id,question_id from public.mistakes on conflict(user_id,question_id) do nothing;

create or replace function public.track_mistake_review() returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
begin
 if not new.is_correct then
  insert into public.mistake_reviews(user_id,question_id,last_attempt_id,last_result)
   values(new.user_id,new.question_id,new.id,false)
   on conflict(user_id,question_id) do update set status='待复习',correct_streak=0,
    review_count=mistake_reviews.review_count+1,last_attempt_id=new.id,last_result=false;
 else
  update public.mistake_reviews set status=case when status='已掌握' then status else '复练中' end,
   review_count=review_count+1,correct_streak=correct_streak+case when new.selected_answer like 'self:%' or new.question_id like '%-written-%' then 0 else 1 end,
   last_attempt_id=new.id,last_result=true where user_id=new.user_id and question_id=new.question_id;
 end if;
 return new;
end $$;
revoke all on function public.track_mistake_review() from public,anon,authenticated;
drop trigger if exists track_mistake_review on public.practice_attempts;
create trigger track_mistake_review after insert on public.practice_attempts for each row execute function public.track_mistake_review();

-- An authenticated atomic save: retries of the same run never create duplicate attempts.
-- This is a self-study assessment; written scores are student self-assessments.
create or replace function public.save_chapter_assessment(p_run jsonb,p_items jsonb) returns uuid
language plpgsql security definer set search_path=public,pg_temp as $$
declare uid uuid:=auth.uid(); run_id uuid; item jsonb; inserted_id uuid;
begin
 if uid is null then raise exception 'Authentication required'; end if;
 if jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items)<>12 or octet_length(p_run::text)>100000 or octet_length(p_items::text)>150000 then raise exception 'Invalid assessment'; end if;
 run_id=(p_run->>'id')::uuid;
 if exists(select 1 from public.chapter_assessments where id=run_id and user_id<>uid) then raise exception 'Assessment unavailable'; end if;
 if (p_run->>'objective')::integer not between 0 and 36 or (p_run->>'selfScore')::integer not between 0 and 24 or (p_run->>'submittedAt')::timestamptz<(p_run->>'startedAt')::timestamptz then raise exception 'Invalid scores or time'; end if;
 insert into public.chapter_assessments(id,user_id,chapter,title,started_at,submitted_at,objective_score,self_score,payload)
 values(run_id,uid,p_run->>'chapter',p_run->>'title',(p_run->>'startedAt')::timestamptz,(p_run->>'submittedAt')::timestamptz,(p_run->>'objective')::integer,(p_run->>'selfScore')::integer,p_run)
 on conflict(id) do nothing returning id into inserted_id;
 if inserted_id is null then
  if exists(select 1 from public.chapter_assessments where id=run_id and user_id=uid and payload=p_run) then return run_id; end if;
  raise exception 'Assessment already saved with different answers';
 end if;
 for item in select value from jsonb_array_elements(p_items) loop
  if coalesce(length(item->>'question_id'),0)=0 or coalesce(length(item->>'answer'),0)>5000 or item->>'topic' is null or item->>'question' is null or item->>'correct_answer' is null or item->>'is_correct' is null then raise exception 'Invalid answer'; end if;
  insert into public.practice_attempts(user_id,question_id,topic,selected_answer,correct_answer,is_correct)
  values(uid,item->>'question_id',item->>'topic',coalesce(item->>'answer',''),item->>'correct_answer',(item->>'is_correct')::boolean);
  if not (item->>'is_correct')::boolean then
   insert into public.mistakes(user_id,question_id,topic,question,user_answer,correct_answer,explanation)
   values(uid,item->>'question_id',item->>'topic',item->>'question',coalesce(item->>'answer',''),item->>'correct_answer',item->>'explanation')
   on conflict(user_id,question_id) do update set user_answer=excluded.user_answer,correct_answer=excluded.correct_answer,explanation=excluded.explanation;
  end if;
 end loop;
 return run_id;
end $$;
revoke all on function public.save_chapter_assessment(jsonb,jsonb) from public,anon;
grant execute on function public.save_chapter_assessment(jsonb,jsonb) to authenticated;
commit;
